export interface Guide {
  slug: string;
  /** 검색 의도 그대로의 질문 — h1 아래 그대로 노출하고 FAQ 스키마의 첫 질문이 된다. */
  question: string;
  /** 페이지 제목(h1). 질문형보다 명사형이 클릭률이 높다. */
  title: string;
  /** 목록에 제목과 함께 보이는 한 줄. 질문을 다시 적지 말고 **무엇이 들어 있는지**를 적는다. */
  lead: string;
  /** ⚠️ 결론 한 문단. AI 답변엔진이 인용하는 건 대개 여기다. 3~4문장 안에서 끝낼 것. */
  answer: string;
  /** meta description. 155자 안쪽. */
  description: string;
  /** 이 가이드가 노리는 검색어. **다른 가이드와 겹치면 안 된다.** */
  keywords: string[];
  body: GuideBody;
  species?: Species;
  faq: { q: string; a: string }[];
  sources: { org: string; title: string; url: string }[];
  /** 관련 가이드 slug — 내부 링크. 서로 물리게 해서 고아 페이지를 만들지 않는다. */
  related: string[];
  /** body 'law' — 핵심 사실 한 줄씩 */
  points?: string[];
  /** body 'law' — 위반하면(과태료·처벌) */
  penalties?: { what: string; amount: string }[];
  /** body 'law' — 시행일(있으면) */
  effective?: string;
}

